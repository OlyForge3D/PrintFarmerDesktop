// Builds the compact, line-addressed index over `.squad/decisions.md` and
// `.squad/holds.md`.
//
// THE PROBLEM. Ralph's standing instruction is "read `.squad/decisions.md`;
// it is authoritative". That file is 380+ KB across 225 sections, and every
// round reads all of it to consult two or three. The cost is paid on every
// round whether or not any decision bears on what the round does, and it is
// paid FIRST, before the round knows which sections it will need — so it
// cannot be avoided by reading less carefully.
//
// The fix is not to summarise the decisions. A summary is a second copy that
// drifts, and a drifted summary of a policy file is worse than no summary,
// because it answers. The fix is an INDEX: the authoritative text stays exactly
// where it is and stays the only copy, and this file records where each section
// begins and ends so a round can read the three sections it needs by line range
// instead of the whole corpus.
//
// The index is GENERATED and CHECKED, never hand-maintained. `--check` fails
// when the committed index does not match a regeneration from the current
// sources, so a decision appended without refreshing the index is a failing
// check rather than a pointer that silently addresses the wrong lines. That is
// the same failure mode as `.squad/decisions.md`'s own line-number citations
// (#199): a stale line number keeps resolving, and points somewhere else.
//
// No shebang: imported by tests/squadDecisionsIndex.test.ts.

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';

export const INDEXED_SOURCES = Object.freeze([
  '.squad/decisions.md',
  '.squad/holds.md',
]);

export const INDEX_PATH = '.squad/decisions-index.md';

export const GENERATED_BANNER =
  '<!-- GENERATED by scripts/squad-decisions-index.mjs — do not edit by hand. -->';

const DATE_PATTERN = /(\d{4}-\d{2}-\d{2})/;

/**
 * Split a markdown document into addressable sections at `##`/`###` headings.
 *
 * Line numbers are 1-based and INCLUSIVE at both ends, matching `sed -n
 * 'a,bp'` and `Select-Object -Skip/-First` arithmetic, so a reader can act on
 * a range without converting it. An off-by-one here is invisible: the read
 * succeeds and returns a section boundary's worth of the neighbouring entry.
 */
export function parseSections(markdown, { source = 'unknown' } = {}) {
  const lines = String(markdown ?? '').split(/\r?\n/);
  const sections = [];

  lines.forEach((line, index) => {
    const match = /^(#{2,3})\s+(.*\S)\s*$/.exec(line);
    if (!match) return;
    sections.push({
      source,
      level: match[1].length,
      title: match[2],
      date: DATE_PATTERN.exec(match[2])?.[1] ?? null,
      startLine: index + 1,
      endLine: lines.length,
    });
  });

  for (let index = 0; index < sections.length - 1; index += 1) {
    sections[index].endLine = sections[index + 1].startLine - 1;
  }

  return sections;
}

/**
 * Issue numbers a section names, so a round holding an issue number can find
 * the decisions about it without reading titles.
 *
 * Scoped to `#123` tokens in the HEADING only. Scanning bodies matches every
 * incidental cross-reference and produces an index where most issues point at
 * most sections, which is the same as pointing at none.
 */
export function issueReferences(title) {
  return [
    ...new Set(
      [...String(title).matchAll(/#(\d{1,5})\b/g)].map((m) => Number(m[1])),
    ),
  ]
    .filter((value) => Number.isInteger(value) && value > 0)
    .sort((a, b) => a - b);
}

/**
 * The index document.
 *
 * One line per section, and nothing else. Every field a reader needs to decide
 * whether to open the section (date, issues, title) and to open it precisely
 * (source, line range). No excerpt: an excerpt is a summary wearing a smaller
 * hat, and it drifts the same way.
 */
export function renderIndex(sectionsBySource) {
  const out = [
    '# Decisions and holds — line index',
    '',
    GENERATED_BANNER,
    '',
    'Read the sections you need, not the corpus. Each row addresses an exact',
    'inclusive line range in the named source:',
    '',
    '```bash',
    "sed -n '120,168p' .squad/decisions.md          # POSIX",
    '```',
    '',
    '```powershell',
    'Get-Content .squad/decisions.md | Select-Object -Skip 119 -First 49   # Windows',
    '```',
    '',
    'Regenerate with `npm run squad:index`; `npm run squad:index -- --check`',
    'fails when this file no longer matches its sources.',
    '',
  ];

  for (const [source, sections] of sectionsBySource) {
    out.push(`## ${source} — ${sections.length} sections`, '');
    out.push('| lines | date | issues | section |');
    out.push('| ----- | ---- | ------ | ------- |');
    for (const section of sections) {
      const issues = issueReferences(section.title);
      out.push(
        `| ${section.startLine}-${section.endLine} | ${section.date ?? '—'} | ` +
          `${issues.length > 0 ? issues.map((n) => `#${n}`).join(' ') : '—'} | ` +
          `${section.title.replace(/\|/g, '\\|')} |`,
      );
    }
    out.push('');
  }

  return `${out.join('\n').replace(/\n+$/, '')}\n`;
}

export function buildIndex(sources) {
  const bySource = new Map();
  for (const { path: source, contents } of sources) {
    bySource.set(source, parseSections(contents, { source }));
  }
  return renderIndex(bySource);
}

/**
 * Look a topic up without reading the corpus.
 *
 * Matches issue numbers exactly and title text case-insensitively, and returns
 * ranges. Exposed for tests and for callers that would otherwise grep the
 * index with a regex of their own devising.
 */
export function lookup(sections, query) {
  const term = String(query ?? '')
    .trim()
    .toLowerCase();
  if (term.length === 0) return [];
  const asIssue = /^#?(\d{1,5})$/.exec(term);
  return sections.filter((section) => {
    if (asIssue) {
      return issueReferences(section.title).includes(Number(asIssue[1]));
    }
    return section.title.toLowerCase().includes(term);
  });
}

function readSources(repoRoot) {
  return INDEXED_SOURCES.map((source) => ({
    path: source,
    contents: readFileSync(path.join(repoRoot, source), 'utf8'),
  }));
}

async function main() {
  const argv = process.argv.slice(2);
  const repoRoot = process.cwd();
  const rendered = buildIndex(readSources(repoRoot));
  const target = path.join(repoRoot, INDEX_PATH);

  if (argv.includes('--check')) {
    let existing = null;
    try {
      existing = readFileSync(target, 'utf8');
    } catch {
      process.stderr.write(
        `${INDEX_PATH} is missing; run \`npm run squad:index\`\n`,
      );
      return 1;
    }
    if (existing !== rendered) {
      process.stderr.write(
        `${INDEX_PATH} is stale; run \`npm run squad:index\` and commit the result\n`,
      );
      return 1;
    }
    process.stdout.write(`${INDEX_PATH} is current\n`);
    return 0;
  }

  writeFileSync(target, rendered, 'utf8');
  process.stdout.write(`wrote ${INDEX_PATH}\n`);
  return 0;
}

if (
  process.argv[1] &&
  path
    .resolve(process.argv[1])
    .endsWith(path.join('scripts', 'squad-decisions-index.mjs'))
) {
  main()
    .then((code) => process.exit(code))
    .catch((error) => {
      process.stderr.write(`squad-decisions-index: ${error.message}\n`);
      process.exit(2);
    });
}
